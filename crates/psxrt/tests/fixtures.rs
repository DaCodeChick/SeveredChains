//! The test-data contract, enforced.
//!
//! Golden fixtures are the fixed input half of every differential test in this crate: a fixture
//! holds what an independent oracle produced, and the code under test is judged against it. That
//! only means something while the fixture is what the oracle produced, so this file pins four
//! things that would otherwise be maintained by memory:
//!
//! * the inventory — which fixtures exist, and how many;
//! * their bytes — size and digest, so an edited or truncated fixture is a failure rather than a
//!   changed expectation;
//! * their provenance — the oracle, the derivation steps and the seed recorded in
//!   `fixtures.provenance`, because a fingerprint cannot tell anyone what a file *is*;
//! * the copies — the target-directory copies that a run-time reader would use, which must be
//!   byte-identical to the canonical files that the compile-time readers embed.
//!
//! # Where the data lives, and how a test reaches it
//!
//! Canonical: `crates/psxrt/testdata/`, registered in `fixtures.manifest` (bytes) and
//! `fixtures.provenance` (origin), regenerated by the oracle programs under `generators/`.
//! Compile-time readers embed it with `include_str!("../testdata/<file>")`; run-time readers will
//! use `<target>/testdata/psxrt/<file>`, materialised by `scripts/prepare_test_fixtures.sh`
//! (`make test-prepare`, and `make test` runs it first). The two paths must agree byte for byte,
//! which is what the copy test below checks.
//!
//! # Adding a fixture
//!
//! Generate it from an independent oracle, add its block to `fixtures.provenance`, register it
//! with `scripts/prepare_test_fixtures.sh --write`, and add its line to `PINNED` here. The lists
//! are deliberate: the manifest is what the tooling verifies, `PINNED` is what the test suite
//! verifies, and a fixture that reaches only one of them is a fixture nobody checked in.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

/// Every fixture this crate's tests read, with the bytes they were generated with.
///
/// `None` in the second field would mean "size not pinned"; there is no such entry, and adding
/// one should be a decision rather than a default.
const PINNED: &[(&str, u64, &str)] = &[
    ("rng_lcg15.txt", 174_969, "41c57e506597403e"),
    ("rng_lcg16.txt", 201_225, "e6f0416585f50a45"),
    ("rng_random48.txt", 750_251, "dc162733dcbcbf6b"),
    ("script_gate.txt", 225, "916523f2f6cb722f"),
    ("timing_matrix.txt", 3_881, "0aff218267d288b5"),
    ("trig_grid.txt", 262_461, "d631327e0a9ab7a4"),
    ("trig_strictmath_divergences.txt", 57, "d5c3e651a3e081ba"),
];

/// The same bytes the compile-time readers embed, spelled out so the embedding is what is
/// checked and not merely assumed.
const EMBEDDED_RANDOM48: &str = include_str!("../testdata/rng_random48.txt");
const EMBEDDED_LCG16: &str = include_str!("../testdata/rng_lcg16.txt");
const EMBEDDED_LCG15: &str = include_str!("../testdata/rng_lcg15.txt");
const EMBEDDED_TRIG_GRID: &str = include_str!("../testdata/trig_grid.txt");
const EMBEDDED_TRIG_DIVERGENCES: &str = include_str!("../testdata/trig_strictmath_divergences.txt");
const EMBEDDED_TIMING_MATRIX: &str = include_str!("../testdata/timing_matrix.txt");
const EMBEDDED_SCRIPT_GATE: &str = include_str!("../testdata/script_gate.txt");

fn canonical_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("testdata")
}

/// Where a run-time reader looks, honouring `CARGO_TARGET_DIR` the way the prepare script does.
fn target_dir() -> PathBuf {
    if let Ok(set) = std::env::var("CARGO_TARGET_DIR") {
        return PathBuf::from(set).join("testdata").join("psxrt");
    }
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../target/testdata/psxrt")
}

/// FNV-1a over 64 bits. Test-only, and deliberately not a hash function worth trusting with
/// anything: it exists so "this file changed" is detectable without pulling a dependency into a
/// platform crate for a test helper.
fn fingerprint(bytes: &[u8]) -> String {
    let mut value: u64 = 0xcbf2_9ce4_8422_2325;
    for byte in bytes {
        value ^= u64::from(*byte);
        value = value.wrapping_mul(0x0000_0100_0000_01b3);
    }
    format!("{value:016x}")
}

fn pinned(name: &str) -> Option<&'static (&'static str, u64, &'static str)> {
    PINNED.iter().find(|entry| entry.0 == name)
}

/// The fixture set is exactly the registered set — same names, same count.
///
/// A fixture dropped from `testdata` does not fail anything on its own: `include_str!` of a
/// missing file is a compile error, but a fixture that a test stopped reading would linger as
/// dead weight, and a new one would go unverified. Pinning the inventory makes both visible.
#[test]
fn the_fixture_inventory_is_exactly_what_is_pinned() {
    let dir = canonical_dir();
    let on_disk: Vec<String> = fs::read_dir(&dir)
        .unwrap_or_else(|error| panic!("{} is not readable: {error}", dir.display()))
        .map(|entry| entry.expect("a readable directory entry").path())
        .filter(|path| path.is_file() && path.extension().is_some_and(|ext| ext == "txt"))
        .map(|path| path.file_name().unwrap().to_string_lossy().into_owned())
        .collect();

    let unlisted: Vec<&str> = on_disk
        .iter()
        .map(String::as_str)
        .filter(|name| pinned(name).is_none())
        .collect();
    let missing: Vec<&str> = PINNED
        .iter()
        .map(|entry| entry.0)
        .filter(|name| !on_disk.iter().any(|found| found.as_str() == *name))
        .collect();

    assert!(
        unlisted.is_empty(),
        "fixtures present in {} but not pinned: {unlisted:?}",
        dir.display()
    );
    assert!(
        missing.is_empty(),
        "pinned fixtures missing from {}: {missing:?}",
        dir.display()
    );
    assert_eq!(
        on_disk.len(),
        7,
        "the number of fixtures is part of the contract"
    );
    assert_eq!(
        on_disk.len(),
        PINNED.len(),
        "PINNED and the directory must be the same census"
    );
}

/// Every fixture's bytes are the bytes it was generated with — on disk and as embedded.
///
/// The two halves are not redundant. A file can be edited in place, which changes the embedded
/// copy at the next rebuild and would otherwise only show up as a golden test failing with a
/// message about a value mismatch; or the working tree can be fine while a stale target copy is
/// what a run-time reader picks up.
#[test]
fn every_fixtures_bytes_are_the_bytes_it_was_generated_with() {
    let dir = canonical_dir();
    let mut drift = Vec::new();

    for (name, size, digest) in PINNED {
        let path = dir.join(name);
        let bytes = fs::read(&path)
            .unwrap_or_else(|error| panic!("{} is not readable: {error}", path.display()));
        if bytes.len() as u64 != *size || fingerprint(&bytes) != *digest {
            drift.push(format!(
                "{name}: on disk is {} bytes {}",
                bytes.len(),
                fingerprint(&bytes)
            ));
        }
    }

    // The embedded copies, checked with the same fingerprints. This is the assertion that makes
    // "the test compares against the oracle output" true of the binary that actually ran.
    for (name, contents) in [
        ("rng_random48.txt", EMBEDDED_RANDOM48),
        ("rng_lcg16.txt", EMBEDDED_LCG16),
        ("rng_lcg15.txt", EMBEDDED_LCG15),
        ("trig_grid.txt", EMBEDDED_TRIG_GRID),
        ("trig_strictmath_divergences.txt", EMBEDDED_TRIG_DIVERGENCES),
        ("timing_matrix.txt", EMBEDDED_TIMING_MATRIX),
        ("script_gate.txt", EMBEDDED_SCRIPT_GATE),
    ] {
        let (size, digest) = pinned(name)
            .map(|entry| (entry.1, entry.2))
            .unwrap_or_else(|| panic!("{name} is embedded but not pinned"));
        assert_eq!(
            contents.len() as u64,
            size,
            "{name}: embedded length is not the pinned size"
        );
        assert_eq!(
            fingerprint(contents.as_bytes()),
            digest,
            "{name}: the embedded bytes are not the generated bytes — regenerate with the \
             oracle under testdata/generators/, or run prepare_test_fixtures.sh --write after \
             reviewing the change"
        );
    }

    assert!(
        drift.is_empty(),
        "fixtures that drifted from their recorded fingerprints:\n{}",
        drift.join("\n")
    );
}

/// The manifest and the pinned inventory say the same thing.
#[test]
fn the_manifest_agrees_with_the_pinned_inventory() {
    let path = canonical_dir().join("fixtures.manifest");
    let text = fs::read_to_string(&path)
        .unwrap_or_else(|error| panic!("{} is not readable: {error}", path.display()));

    let mut problems = Vec::new();
    let mut lines = 0;
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        lines += 1;
        let fields: Vec<&str> = line.split(',').map(str::trim).collect();
        if fields.len() != 3 {
            problems.push(format!("malformed line: {line}"));
            continue;
        }
        match pinned(fields[0]) {
            None => problems.push(format!("{} is registered but not pinned", fields[0])),
            Some((_, size, digest)) => {
                if fields[1] != size.to_string() || fields[2] != *digest {
                    problems.push(format!(
                        "{}: manifest says {} bytes {}, the suite pins {} bytes {}",
                        fields[0], fields[1], fields[2], size, digest
                    ));
                }
            }
        }
    }

    assert_eq!(lines, PINNED.len(), "one manifest line per pinned fixture");
    assert!(
        problems.is_empty(),
        "the manifest and the suite disagree:\n{}",
        problems.join("\n")
    );
}

/// If a target-directory copy exists, it is the canonical data.
///
/// Absent is a legitimate state — `cargo test` alone does not populate it — so this reports
/// rather than fails. Present-but-different is not legitimate, and a run-time reader would have
/// been comparing against something nobody generated.
#[test]
fn a_target_copy_never_disagrees_with_the_canonical_data() {
    let target = target_dir();
    if !target.is_dir() {
        eprintln!(
            "note: {} does not exist; run `make test-prepare` (or \
             scripts/prepare_test_fixtures.sh) to populate it",
            target.display()
        );
        return;
    }

    let mut problems = Vec::new();
    for (name, _size, digest) in PINNED {
        let canonical = canonical_dir().join(name);
        let copy = target.join(name);
        let wanted = fs::read(&canonical).expect("the canonical fixture is readable");
        if !copy.is_file() {
            problems.push(format!("{name}: no copy in {}", target.display()));
            continue;
        }
        let found = fs::read(&copy).expect("the copy is readable");
        if found != wanted {
            problems.push(format!(
                "{name}: the copy in {} is not the canonical file ({} bytes against {})",
                target.display(),
                found.len(),
                wanted.len()
            ));
        }
        assert_eq!(
            fingerprint(&wanted),
            *digest,
            "{name}: the canonical file drifted"
        );
    }

    assert!(
        problems.is_empty(),
        "target copies that cannot be trusted:\n{}",
        problems.join("\n")
    );
}

/// The per-crate fixture census, read across the whole workspace.
///
/// "Seven fixtures, all in `psxrt`, and no other crate carries any" is a claim in `README.md`,
/// and a claim in a document is only true until somebody drops a file somewhere. This walks every
/// crate's `testdata/` so the README and the disk cannot be describing different things, and it
/// requires any crate that carries fixtures to register them: data with no manifest is data
/// whose provenance nobody can re-check.
#[test]
fn the_fixture_counts_are_the_expected_ones() {
    let crates_dir = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("the crate lives under crates/")
        .to_path_buf();

    let mut census: Vec<String> = Vec::new();
    let mut unregistered: Vec<String> = Vec::new();

    for entry in fs::read_dir(&crates_dir)
        .unwrap_or_else(|error| panic!("{} is not readable: {error}", crates_dir.display()))
    {
        let crate_dir = entry.expect("a readable directory entry").path();
        let data = crate_dir.join("testdata");
        if !data.is_dir() {
            continue;
        }
        let name = crate_dir
            .file_name()
            .unwrap()
            .to_string_lossy()
            .into_owned();
        let files: Vec<String> = fs::read_dir(&data)
            .expect("testdata is readable")
            .map(|item| item.expect("a readable directory entry").path())
            .filter(|path| path.is_file() && path.extension().is_some_and(|ext| ext == "txt"))
            .map(|path| path.file_name().unwrap().to_string_lossy().into_owned())
            .collect();
        census.push(format!("{name}: {}", files.len()));
        if !data.join("fixtures.manifest").is_file() {
            unregistered.push(name);
        }
    }

    census.sort();
    assert_eq!(
        census,
        vec!["psxrt: 7".to_string()],
        "the fixture census no longer matches the one README.md and this file describe"
    );
    assert!(
        unregistered.is_empty(),
        "crates carrying fixtures with no manifest to register them: {unregistered:?}"
    );
}

/// Every fixture records where its expected values came from, and that source still exists.
///
/// A fingerprint proves a file has not changed; it says nothing about whether anyone still knows
/// what the file is. `fixtures.provenance` carries the oracle, the derivation and the seed for
/// each fixture, which is the project's rule for golden data (planning/05 §3 rule 1) and the only
/// thing that lets a later reader re-derive a fixture instead of regenerating it from the code it
/// is supposed to check. So this checks that every fixture has all three fields, that a
/// derivation is long enough to actually be steps, and that an oracle named as a path is a file
/// still in the tree — provenance pointing at a program nobody kept is decoration.
#[test]
fn every_fixture_records_where_its_expected_values_came_from() {
    let dir = canonical_dir();
    let path = dir.join("fixtures.provenance");
    let text = fs::read_to_string(&path)
        .unwrap_or_else(|error| panic!("{} is not readable: {error}", path.display()));

    // `[name]` opens a block, `key = value` fills it, anything else is a comment. The open
    // block is tracked by name rather than by "the last one": a BTreeMap is ordered by key, so
    // "last" would mean `trig_strictmath_divergences.txt` for three quarters of the file.
    let mut records: BTreeMap<String, BTreeMap<String, String>> = BTreeMap::new();
    let mut open: Option<String> = None;
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        if let Some(name) = line
            .strip_prefix('[')
            .and_then(|rest| rest.strip_suffix(']'))
        {
            records.insert(name.to_string(), BTreeMap::new());
            open = Some(name.to_string());
            continue;
        }
        let Some((key, value)) = line.split_once('=') else {
            panic!(
                "{}: {line} is neither a block header nor a key = value line",
                path.display()
            );
        };
        match open.as_deref().and_then(|name| records.get_mut(name)) {
            None => panic!(
                "{}: `{line}` appears before any [fixture] header",
                path.display()
            ),
            Some(block) => {
                block.insert(key.trim().to_string(), value.trim().to_string());
            }
        }
    }

    let mut problems = Vec::new();
    for (name, _size, _digest) in PINNED {
        let Some(record) = records.get(*name) else {
            problems.push(format!("{name}: no provenance block at all"));
            continue;
        };
        for key in ["oracle", "seed"] {
            if !record.get(key).is_some_and(|value| !value.is_empty()) {
                problems.push(format!(
                    "{name}: `{key}` is missing, so the file cannot be re-made"
                ));
            }
        }
        if !record
            .get("derivation")
            .is_some_and(|value| value.len() >= 20)
        {
            problems.push(format!(
                "{name}: `derivation` is missing or too short to be steps — a one-word note is \
                 not a derivation"
            ));
        }
        if let Some(oracle) = record.get("oracle") {
            let first = oracle
                .split_whitespace()
                .next()
                .unwrap_or("")
                .trim_end_matches(',')
                .to_string();
            if first.contains('/') {
                let crate_root = Path::new(env!("CARGO_MANIFEST_DIR"));
                if !crate_root.join(&first).is_file() {
                    problems.push(format!(
                        "{name}: names {first} as its oracle and that file is not in the tree"
                    ));
                }
            }
        }
    }

    for name in records.keys() {
        if pinned(name).is_none() {
            problems.push(format!(
                "{name} has a provenance block but is not a registered fixture"
            ));
        }
    }

    assert!(
        problems.is_empty(),
        "provenance that would not survive a refresh:\n{}",
        problems.join("\n")
    );
}
